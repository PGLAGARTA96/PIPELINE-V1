def precision(correctas, detectadas):
    return correctas / detectadas if detectadas > 0 else 0

def recall(correctas, reales):
    return correctas / reales if reales > 0 else 0

# ===============================
# EVALUACIÓN PRECISIÓN / RECALL
# ===============================

def evaluar_precision_recall_por_tipo(entidades_detectadas, gold_standard, umbral=0.5):
    resultados = {}

    for tipo in ["ROL", "ACCIÓN", "OBJETO", "BENEFICIO"]:
        correctas = 0
        detectadas = 0
        reales = 0

        for auto, gold in zip(entidades_detectadas, gold_standard):
            auto_vals = auto.get(tipo, [])
            gold_vals = gold.get("anotaciones", {}).get(tipo, [])

            detectadas += len(auto_vals)
            reales += len(gold_vals)

            for a in auto_vals:
                a = a.lower().strip()

                # filtros semánticos
                if tipo == "ACCIÓN" and a in VERBOS_GENERICOS:
                    continue
                if tipo == "BENEFICIO" and not beneficio_valido(a):
                    continue

                for g in gold_vals:
                    g = g.lower().strip()

                    if overlap_parcial(a, g) >= umbral:
                        correctas += 1
                        break

        resultados[tipo] = {
            "precision": round(precision(correctas, detectadas), 2),
            "recall": round(recall(correctas, reales), 2)
        }

    return resultados

# ===============================
