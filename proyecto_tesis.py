def algoritmo_7_generar_gold(
    historias_originales,
    entidades_detectadas,
    nombre_dataset,
    ruta_salida,
    limite=50
):
    gold = []

    for i, (texto, entidades) in enumerate(
        zip(historias_originales[:limite], entidades_detectadas[:limite]),
        start=1
    ):
        anotaciones = {}

        if entidades.get("ROL"):
            anotaciones["ROL"] = entidades["ROL"]

        acciones_filtradas = [
            a for a in entidades.get("ACCIÓN", [])
            if a.lower() not in VERBOS_GENERICOS
        ]
        if acciones_filtradas:
            anotaciones["ACCIÓN"] = acciones_filtradas

        if entidades.get("OBJETO"):
            anotaciones["OBJETO"] = entidades["OBJETO"]

