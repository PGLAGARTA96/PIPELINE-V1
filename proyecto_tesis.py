def algoritmo_6_metricas_calidad(entidades_por_historia, tokens_por_historia):
    resultados = []

    for entidades, tokens in zip(entidades_por_historia, tokens_por_historia):
        metricas = {
            "completitud": metric_completitud(entidades),
            "atomicidad": metric_atomicidad(entidades),
            "claridad": metric_claridad(entidades),
            "concisión": metric_concision(tokens)
        }

        metricas["calidad_global"] = puntuacion_global(metricas)
        resultados.append(metricas)

    return resultados

