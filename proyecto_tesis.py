def algoritmo_3_reconocimiento_entidades_con_contexto(pos_por_historia):
    resultados = []

    for historia in pos_por_historia:
        entidades = {
            "ROL": [],
            "ACCIÓN": [],
            "OBJETO": [],
            "BENEFICIO": [],
            "CONTEXTO": []
        }

        tokens = [t[0].lower() for t in historia]

        # -------- ROL --------
        if "como" in tokens:
            idx = tokens.index("como")
            for i in range(idx + 1, len(historia)):
                token, pos = historia[i]
                if pos == "NOUN":
                    entidades["ROL"].append(token)
                    break

        # -------- ACCIÓN --------
        accion = extraer_accion_semantica(historia)
        if accion:
          entidades["ACCIÓN"].append(accion)


        # -------- OBJETO --------
        accion_encontrada = False
        for token, pos in historia:
            if pos == "VERB" and token.lower() not in VERBOS_DEBILES:
                accion_encontrada = True
                continue
            if accion_encontrada and pos == "NOUN":
                entidades["OBJETO"].append(token)
                break


        # -------- BENEFICIO --------
        beneficio = extraer_beneficio(historia)
        if beneficio:
            entidades["BENEFICIO"].append(beneficio)

        # -------- CONTEXTO --------
        entidades["CONTEXTO"] = extraer_contexto(historia)

        resultados.append(entidades)

    return resultados

