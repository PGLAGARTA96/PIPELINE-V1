def overlap_parcial(a, b):
    """
    Calcula solapamiento léxico entre dos expresiones
    """
    set_a = set(a.split())
    set_b = set(b.split())

    if not set_a or not set_b:
        return 0

    return len(set_a & set_b) / max(len(set_a), len(set_b))

