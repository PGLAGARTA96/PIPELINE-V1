def evaluar_tiempo_pipeline(
    tokens_fn,
    pos_fn,
    entidades_fn,
    relaciones_fn,
    metricas_fn,
    entrada
):
    inicio = time.time()

    tokens = tokens_fn(entrada)
    pos = pos_fn(tokens)
    entidades = entidades_fn(pos)
    relaciones = relaciones_fn(entidades)
    metricas = metricas_fn(entidades, tokens)

    fin = time.time()

    tiempo_total = fin - inicio
    tiempo_promedio = tiempo_total / len(tokens)

    return {
        "tiempo_total_segundos": round(tiempo_total, 4),
        "tiempo_promedio_por_historia": round(tiempo_promedio, 4)
    }

