# Conectores lingüísticos para BENEFICIO
CONECTORES_BENEFICIO = [
    ["para"],
    ["para", "que"],
    ["de", "modo", "que"],
    ["a", "fin", "de"],
    ["con", "el", "fin", "de"]
]

def extraer_beneficio(historia):
    tokens = [t[0].lower() for t in historia]
    posiciones = []

    for conector in CONECTORES_BENEFICIO:
        n = len(conector)
        for i in range(len(tokens) - n):
            if tokens[i:i+n] == conector:
                posiciones.append(i + n)

    if posiciones:
        inicio = max(posiciones)
        beneficio = [
            historia[j][0]
            for j in range(inicio, len(historia))
            if historia[j][1] != "PUNCT"
        ]
        return " ".join(beneficio)

    return None



def extraer_contexto(historia):
    """
    Extrae un contexto semántico básico a partir de sustantivos
    y modificadores cercanos
    """
    contexto = []
    for i, (token, pos) in enumerate(historia):
        if pos == "NOUN":
            frase = [token]

            for j in range(i + 1, min(i + 4, len(historia))):
                t, p = historia[j]
                if p in ["ADJ", "ADP", "NOUN"]:
                    frase.append(t)
                else:
                    break

            contexto.append(" ".join(frase))

    return list(set(contexto))

VERBOS_DEBILES = {
    "quiero", "querer",
    "poder", "puedo", "pueda",
    "gustaría", "desearía", "necesito"
}

def extraer_accion_semantica(historia):
    """
    Extrae el primer verbo semántico relevante,
    ignorando verbos débiles como 'quiero'
    """
    for token, pos in historia:
        if pos == "VERB" and token.lower() not in VERBOS_DEBILES:
            return token
    return None


