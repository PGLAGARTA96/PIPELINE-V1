def metric_completitud(entidades):
    requeridos = ["ROL", "ACCIÓN", "OBJETO", "BENEFICIO"]
    presentes = sum(1 for r in requeridos if entidades.get(r))
    return presentes / len(requeridos)


def metric_atomicidad(entidades):
    acciones = entidades.get("ACCIÓN", [])
    return 1.0 if len(acciones) == 1 else 0.0


def metric_concision(tokens, max_tokens=30):
    if not tokens:
        return 0.0
    if len(tokens) <= max_tokens:
        return 1.0
    exceso = len(tokens) - max_tokens
    return max(0.5, 1 - exceso / max_tokens)


def metric_claridad(entidades):
    verbos_vagos = {
        "hacer", "manejar", "gestionar",
        "realizar", "permitir", "poder"
    }
    acciones = [a.lower() for a in entidades.get("ACCIÓN", [])]
    if any(v in verbos_vagos for v in acciones):
        return 0.5
    return 1.0


def puntuacion_global(metricas):
    return round(sum(metricas.values()) / len(metricas), 2)

