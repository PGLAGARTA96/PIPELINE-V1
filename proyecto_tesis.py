def evaluar_metricas_globales(metricas_por_historia):
    promedio = {}
    claves = metricas_por_historia[0].keys()

    for k in claves:
        promedio[k] = round(
            sum(m[k] for m in metricas_por_historia) / len(metricas_por_historia), 2
        )

    return promedio

